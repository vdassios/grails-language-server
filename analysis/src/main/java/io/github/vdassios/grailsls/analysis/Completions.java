package io.github.vdassios.grailsls.analysis;

import java.net.URI;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.regex.Pattern;
import java.util.stream.Collectors;

import org.codehaus.groovy.ast.ASTNode;
import org.codehaus.groovy.ast.AnnotatedNode;
import org.codehaus.groovy.ast.ClassNode;
import org.codehaus.groovy.ast.FieldNode;
import org.codehaus.groovy.ast.ImportNode;
import org.codehaus.groovy.ast.MethodNode;
import org.codehaus.groovy.ast.ModuleNode;
import org.codehaus.groovy.ast.PropertyNode;
import org.codehaus.groovy.ast.Variable;
import org.codehaus.groovy.ast.VariableScope;
import org.codehaus.groovy.ast.expr.ClassExpression;
import org.codehaus.groovy.ast.expr.ConstructorCallExpression;
import org.codehaus.groovy.ast.expr.Expression;
import org.codehaus.groovy.ast.expr.MethodCallExpression;
import org.codehaus.groovy.ast.expr.PropertyExpression;
import org.codehaus.groovy.ast.expr.VariableExpression;
import org.codehaus.groovy.ast.stmt.BlockStatement;
import org.codehaus.groovy.ast.stmt.Statement;

import io.github.vdassios.grailsls.api.Completion;
import io.github.vdassios.grailsls.api.CompletionDetail;
import io.github.vdassios.grailsls.api.CompletionList;
import io.github.vdassios.grailsls.api.Range;
import io.github.vdassios.grailsls.api.TextEdit;
import net.prominic.groovyls.compiler.ast.ASTNodeVisitor;
import net.prominic.groovyls.compiler.util.GroovyASTUtils;
import net.prominic.groovyls.compiler.util.GroovydocUtils;

/**
 * Completion over a visited compile. Ported from groovy-language-server's {@code CompletionProvider}, returning
 * {@code api} types. Changes: members come from the receiver's whole type hierarchy (superclasses and all interfaces;
 * trait members are on the class node after the compile), names with a {@code $} (generated by Groovy and Grails) are
 * left out, and signatures and documentation wait for {@link #detail}.
 */
public final class Completions {
  /** Upstream's limit on class items. */
  private static final int MAX_ITEMS = 1000;
  private static final Pattern CONSTRUCTOR_CALL = Pattern.compile(".*new \\w*$");

  private final ASTNodeVisitor ast;
  private final ClasspathTypes classpath;
  private final List<Completion> items = new ArrayList<>();
  /** The declaration behind each item with an id, by id. */
  private final List<ASTNode> declarations = new ArrayList<>();
  private boolean incomplete;

  private Completions(ASTNodeVisitor ast, ClasspathTypes classpath) {
    this.ast = ast;
    this.classpath = classpath;
  }

  /**
   * The candidates at a position, or null when the compile has no node there (the text does not parse).
   *
   * @param classpath classes of the classpath to offer, or null for those of the compile only
   */
  public static Completions at(ASTNodeVisitor ast, URI document, ClasspathTypes classpath, int line, int column) {
    ASTNode offsetNode = ast.getNodeAtLineAndColumn(document, line, column);
    if (offsetNode == null) {
      return null;
    }
    Completions completions = new Completions(ast, classpath);
    completions.populate(offsetNode, line, column);
    return completions;
  }

  /** The text to insert at the position when it does not parse: a name, or a constructor call after {@code new}. */
  public static String placeholder(String lineBeforePosition) {
    return CONSTRUCTOR_CALL.matcher(lineBeforePosition).matches() ? "a()" : "a";
  }

  public CompletionList list() {
    return new CompletionList(items, incomplete);
  }

  /** The declaration behind an item, or null. */
  public ASTNode declaration(int id) {
    return id >= 0 && id < declarations.size() ? declarations.get(id) : null;
  }

  /** Signature and documentation of a declaration. */
  public static CompletionDetail detail(ASTNode declaration, ASTNodeVisitor ast) {
    String documentation = declaration instanceof AnnotatedNode ? GroovydocUtils.groovydocToMarkdownDescription((AnnotatedNode) declaration) : null;
    return new CompletionDetail(Navigation.signature(declaration, ast), documentation);
  }

  private void populate(ASTNode offsetNode, int line, int column) {
    ASTNode parentNode = ast.getParent(offsetNode);
    if (offsetNode instanceof PropertyExpression) {
      fromPropertyExpression((PropertyExpression) offsetNode, line, column);
    } else if (parentNode instanceof PropertyExpression) {
      fromPropertyExpression((PropertyExpression) parentNode, line, column);
    } else if (offsetNode instanceof MethodCallExpression) {
      fromMethodCallExpression((MethodCallExpression) offsetNode, line, column);
    } else if (offsetNode instanceof ConstructorCallExpression) {
      fromConstructorCallExpression((ConstructorCallExpression) offsetNode, line, column);
    } else if (parentNode instanceof MethodCallExpression) {
      fromMethodCallExpression((MethodCallExpression) parentNode, line, column);
    } else if (offsetNode instanceof VariableExpression) {
      VariableExpression variable = (VariableExpression) offsetNode;
      Range range = NodeRanges.of(variable);
      if (range != null) {
        fromScope(variable, prefix(variable.getName(), range, line, column));
      }
    } else if (offsetNode instanceof ImportNode) {
      fromImport((ImportNode) offsetNode, line, column);
    } else if (offsetNode instanceof ClassNode) {
      fromClassNode((ClassNode) offsetNode, line, column);
    } else if (offsetNode instanceof MethodNode || offsetNode instanceof Statement) {
      fromScope(offsetNode, "");
    }
  }

  private void fromPropertyExpression(PropertyExpression expression, int line, int column) {
    Range range = NodeRanges.of(expression.getProperty());
    if (range != null) {
      fromReceiver(expression.getObjectExpression(), expression, prefix(expression.getPropertyAsString(), range, line, column));
    }
  }

  private void fromMethodCallExpression(MethodCallExpression call, int line, int column) {
    Range range = NodeRanges.of(call.getMethod());
    if (range != null) {
      fromReceiver(call.getObjectExpression(), call, prefix(call.getMethodAsString(), range, line, column));
    }
  }

  private void fromConstructorCallExpression(ConstructorCallExpression call, int line, int column) {
    Range range = NodeRanges.of(call.getType());
    if (range != null) {
      types(call, prefix(call.getType().getNameWithoutPackage(), range, line, column), new HashSet<>());
    }
  }

  /** {@code class A extends B}, {@code implements C}: classes and interfaces. */
  private void fromClassNode(ClassNode type, int line, int column) {
    ASTNode parent = ast.getParent(type);
    Range range = NodeRanges.of(type);
    if (!(parent instanceof ClassNode) || range == null) {
      return;
    }
    ClassNode owner = (ClassNode) parent;
    if (type.equals(owner.getUnresolvedSuperClass()) || List.of(owner.getUnresolvedInterfaces()).contains(type)) {
      types(type, prefix(type.getUnresolvedName(), range, line, column), new HashSet<>());
    }
  }

  /** Members of the receiver's type: static ones for a class ({@code Book.}), the others for a value. */
  private void fromReceiver(Expression receiver, ASTNode expression, String prefix) {
    ClassNode type = GroovyASTUtils.getTypeOfReceiver(receiver, expression, ast);
    if (type != null) {
      members(type, receiver instanceof ClassExpression, prefix, new HashSet<>());
    }
  }

  /** Names visible at a node: variables of the enclosing blocks and methods, members of the enclosing classes, classes. */
  private void fromScope(ASTNode node, String prefix) {
    Set<String> names = new HashSet<>();
    for (ASTNode current = node; current != null; current = ast.getParent(current)) {
      if (current instanceof ClassNode) {
        members((ClassNode) current, null, prefix, names);
      } else if (current instanceof MethodNode) {
        variables(((MethodNode) current).getVariableScope(), prefix, names);
      } else if (current instanceof BlockStatement) {
        variables(((BlockStatement) current).getVariableScope(), prefix, names);
      }
    }
    types(node, prefix, names);
  }

  /**
   * Properties and fields, then methods, of a type and its supertypes, nearest first; overloads once. Private members
   * of supertypes are left out, and so are the members of a class whose members cannot be loaded.
   *
   * @param statics true for static members only, false for the others, null for all
   */
  private void members(ClassNode type, Boolean statics, String prefix, Set<String> names) {
    List<ClassNode> hierarchy = hierarchy(type);
    for (ClassNode current : hierarchy) {
      for (PropertyNode property : GroovyASTUtils.members(current::getProperties, List.<PropertyNode>of())) {
        if (statics == null || property.isStatic() == statics) {
          add(property.getName(), Completion.Kind.FIELD, property, prefix, names);
        }
      }
    }
    for (ClassNode current : hierarchy) {
      for (FieldNode field : GroovyASTUtils.members(current::getFields, List.<FieldNode>of())) {
        if ((statics == null || field.isStatic() == statics) && (current == type || !field.isPrivate())) {
          add(field.getName(), Completion.Kind.FIELD, field, prefix, names);
        }
      }
    }
    for (ClassNode current : hierarchy) {
      for (MethodNode method : GroovyASTUtils.members(current::getMethods, List.<MethodNode>of())) {
        if ((statics == null || method.isStatic() == statics) && (current == type || !method.isPrivate()) && !method.isSynthetic()) {
          add(method.getName(), Completion.Kind.METHOD, method, prefix, names);
        }
      }
    }
  }

  /** A type, its superclasses and every interface they implement. A supertype whose class cannot be loaded is skipped. */
  private static List<ClassNode> hierarchy(ClassNode type) {
    Set<ClassNode> seen = new LinkedHashSet<>();
    List<ClassNode> queue = new ArrayList<>();
    queue.add(type);
    for (int i = 0; i < queue.size(); i++) {
      ClassNode current = queue.get(i);
      if (!seen.add(current)) {
        continue;
      }
      try {
        ClassNode superClass = current.getSuperClass();
        if (superClass != null) {
          queue.add(superClass);
        }
        queue.addAll(List.of(current.getInterfaces()));
      } catch (LinkageError e) {
        // a supertype refers to a class missing from the classpath: keep what was found
      }
    }
    return new ArrayList<>(seen);
  }

  private void variables(VariableScope scope, String prefix, Set<String> names) {
    for (Variable variable : scope.getDeclaredVariables().values()) {
      add(variable.getName(), Completion.Kind.VARIABLE, variable instanceof ASTNode ? (ASTNode) variable : null, prefix, names);
    }
  }

  private void add(String name, Completion.Kind kind, ASTNode declaration, String prefix, Set<String> names) {
    if (!name.startsWith(prefix) || name.indexOf('$') >= 0 || !names.add(name)) {
      return;
    }
    items.add(new Completion(name, kind, null, null, null, List.of(), declaration == null ? -1 : remember(declaration)));
  }

  private int remember(ASTNode declaration) {
    declarations.add(declaration);
    return declarations.size() - 1;
  }

  /** Classes of the compile, then of the classpath, whose simple name starts with the prefix; with an import when needed. */
  private void types(ASTNode offsetNode, String prefix, Set<String> names) {
    ModuleNode module = (ModuleNode) GroovyASTUtils.getEnclosingNodeOfType(offsetNode, ModuleNode.class, ast);
    String packageName = module == null ? null : module.getPackageName();
    List<String> imports = imports(module);
    Range importAt = importPosition(module);
    for (ClassNode type : ast.getClassNodes()) {
      if (!roomFor(names)) {
        return;
      }
      String simpleName = type.getNameWithoutPackage();
      if (simpleName.startsWith(prefix) && simpleName.indexOf('$') < 0 && names.add(type.getName())) {
        items.add(new Completion(simpleName, kind(type), type.getPackageName(), null, null, importEdits(type.getName(), type.getPackageName(), packageName, imports, importAt),
            remember(type)));
      }
    }
    if (classpath == null) {
      return;
    }
    for (ClasspathTypes.Type type : classpath.types()) {
      if (!roomFor(names)) {
        return;
      }
      if (type.simpleName.startsWith(prefix) && names.add(type.name)) {
        items.add(new Completion(type.simpleName, type.kind, type.packageName, null, null, importEdits(type.name, type.packageName, packageName, imports, importAt), -1));
      }
    }
  }

  private boolean roomFor(Set<String> names) {
    if (names.size() >= MAX_ITEMS) {
      incomplete = true;
    }
    return !incomplete;
  }

  private static List<TextEdit> importEdits(String className, String classPackage, String packageName, List<String> imports, Range importAt) {
    if (classPackage == null || classPackage.equals(packageName) || imports.contains(className)) {
      return List.of();
    }
    return List.of(new TextEdit(importAt, "import " + className + "\n"));
  }

  /** {@code import a.b.C}: classes and packages whose name starts with what is typed. */
  private void fromImport(ImportNode importNode, int line, int column) {
    Range range = NodeRanges.of(importNode);
    if (range == null) {
      return;
    }
    String typed = importNode.getType().getName();
    // the name only, without "import "
    Range nameRange = new Range(range.endLine, range.endColumn - typed.length(), range.endLine, range.endColumn);
    String prefix = prefix(typed, nameRange, line, column);
    ModuleNode module = (ModuleNode) GroovyASTUtils.getEnclosingNodeOfType(importNode, ModuleNode.class, ast);
    String packageName = module == null ? null : module.getPackageName();
    List<String> imports = imports(module);
    for (ClassNode type : ast.getClassNodes()) {
      String typePackage = type.getPackageName();
      if (typePackage == null || typePackage.isEmpty() || typePackage.equals(packageName) || imports.contains(type.getName())) {
        continue;
      }
      if (type.getName().startsWith(prefix) || type.getNameWithoutPackage().startsWith(prefix)) {
        String sortText = type.getNameWithoutPackage().startsWith(prefix) ? type.getNameWithoutPackage() : null;
        items.add(new Completion(type.getName(), kind(type), null, sortText, nameRange, List.of(), remember(type)));
      }
    }
    if (classpath == null) {
      return;
    }
    for (String classpathPackage : classpath.packages()) {
      if (classpathPackage.startsWith(prefix)) {
        items.add(new Completion(classpathPackage, Completion.Kind.PACKAGE, null, null, nameRange, List.of(), -1));
      }
    }
    for (ClasspathTypes.Type type : classpath.types()) {
      if (type.packageName == null || type.packageName.isEmpty() || type.packageName.equals(packageName) || imports.contains(type.name)) {
        continue;
      }
      if (type.name.startsWith(prefix) || type.simpleName.startsWith(prefix)) {
        String sortText = type.simpleName.startsWith(prefix) ? type.simpleName : null;
        items.add(new Completion(type.name, type.kind, null, sortText, nameRange, List.of(), -1));
      }
    }
  }

  private static List<String> imports(ModuleNode module) {
    return module == null ? List.of() : module.getImports().stream().map(ImportNode::getClassName).collect(Collectors.toList());
  }

  /** The start of the line after the last import, else after the package line, else the top of the file. */
  private static Range importPosition(ModuleNode module) {
    ASTNode after = null;
    if (module != null) {
      List<ImportNode> imports = module.getImports();
      after = imports.isEmpty() ? module.getPackage() : imports.get(imports.size() - 1);
    }
    Range range = after == null ? null : NodeRanges.of(after);
    int line = range == null ? 0 : range.endLine + 1;
    return new Range(line, 0, line, 0);
  }

  private static Completion.Kind kind(ClassNode type) {
    return type.isInterface() ? Completion.Kind.INTERFACE : type.isEnum() ? Completion.Kind.ENUM : Completion.Kind.CLASS;
  }

  /** The part of a name before the position: what is typed so far. */
  private static String prefix(String name, Range range, int line, int column) {
    if (line == range.startLine && column > range.startColumn) {
      int length = column - range.startColumn;
      if (length <= name.length()) {
        return name.substring(0, length).trim();
      }
    }
    return "";
  }
}
